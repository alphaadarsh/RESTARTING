# lets learn  \  
#  \n next line 
#  \t tab space
# \\ backslash
# \' single quote inside string wiith single quote
# \" double quote inside string with double quote

print("Hello\nWorld")  # Output: Hello (next line) World    
print("Hello\tWorld")  # Output: Hello (tab space) World
print("Hello\\World")  # Output: Hello\World
print('It\'s a beautiful day.')  # Output: It's a beautiful day.
print("She said, \"Hello!\"")  # Output: She said, "Hello!"