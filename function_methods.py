#  lets talk about string methods in python. string methods are built-in functions that can be used to manipulate and perform operations on strings. some commonly used string methods are:
# 1. upper(): converts all characters in a string to uppercase.
#   2. lower(): converts all characters in a string to lowercase.
# 3. replace(): replaces a specified substring with another substring in a string.
#  string methods are useful for tasks such as formatting, searching, and modifying strings. they can be called on string objects using dot notation, and they return a new string with the desired modifications. whenever we applu operation it does not change the original string. it returns a new string with the applied operation. it is immutable. we can use string methods to perform various operations on strings, such as changing case, replacing characters, splitting strings, and more. these methods provide a convenient way to manipulate and work with string data in python.  