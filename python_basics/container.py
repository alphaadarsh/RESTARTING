# lets talk about  tuples exaple tuples are immutable data structures in python. they are similar to lists but cannot be changed after creation. they are defined using parentheses () and can contain elements of different data types.
# list lets talk about lists in python. lists are mutable data structures that can hold an ordered collection of items. they are defined using square brackets [] and can contain elements of different data types. lists can be modified by adding, removing, or changing elements.
#  tuple cannot be changed after creation, while lists can be modified. tuples are defined using parentheses (), while lists are defined using square brackets []. tuples are generally used for fixed collections of items, while lists are used for collections that may change over time.

