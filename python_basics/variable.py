# what is variable 

first_name = "John"
last_name = "Doe"

print("Full Name: " + first_name + " " + last_name)  # Output: Full Name: John Doe
print(f"Full Name: {first_name} {last_name}")  # Output: Full Name: John Doe

food = "Pizza"
print("I love " + food)  # Output: I love Pizza
print(f"I love {food}")  # Output: I love Pizza

# variables can also be used in expressions and calculations. For example: 
price = 10
quantity = 5
total_cost = price * quantity
print(f"Total Cost: ${total_cost}")  # Output: Total Cost: $50

